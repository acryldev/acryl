#!/usr/bin/env node
// The launcher as one file with nothing to install: run.js with the journeys, acryl-ui-tui and the workspace's patched pi-tui inlined. The acryl npm
// package ships this file as launcher.js and opens it for a bare `acryl` in a terminal, so `npx acryl` stays small and needs no dependency.
// Usage: node scripts/bundle.mjs <output file>
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'rolldown'

const here = dirname(fileURLToPath(import.meta.url))

/** Write the bundle to `file` and return its path. */
export async function bundleLauncher(file) {
  const out = resolve(file)
  await build({
    input: resolve(here, '..', 'run.js'),
    platform: 'node',
    logLevel: 'warn',
    output: {
      file: out,
      format: 'esm',
      codeSplitting: false,
      banner: '// acryl launcher (spec 050): generated by apps/acryl-launcher-tui/scripts/bundle.mjs. Do not edit; change the sources and bundle again.',
    },
  })
  return out
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const target = process.argv[2]
  if (!target) {
    console.error('usage: node scripts/bundle.mjs <output file>')
    process.exitCode = 2
  } else console.log(await bundleLauncher(target))
}
