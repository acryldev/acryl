#!/usr/bin/env node
// Re-export inventory (spec 038-ui-component-library). Writes contracts/reexports.json: every
// export of @acryl/ui that is NOT a registry item, grouped by where it comes from.
//
// Why this exists: the catalogue sites list a category as built only when one of its componentIds
// resolves to a registry item, so a component this package exports from the app's own primitives
// (Button, Input, Tooltip, Dropdown Menu, Sonner, Status, Tags, Tree, Code Block, Hover Card) read
// as "not yet built" while a consumer could import it. The sites need to know which names are
// provided-but-not-copyable, and that answer has to come from index.ts's own imports rather than a
// second hand-kept list, or the two drift the first time an export is added.
//
// The classification uses the module a name is imported from, which index.ts states exactly:
// './registry/<Name>/<Name>.tsx' is a registry item, '@deepseek-ai/dsh-client-ui-primitives' is a
// re-export of the app's primitives, './contract-adapters.tsx' is a DSH-backed adapter this package
// owns, and anything else is a local helper (roles, slot helpers, version).
//
// Usage: node scripts/generate-reexports.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const INDEX = join(ROOT, 'src/client/index.ts')
// The output path is overridable so tests/reexports.spec.ts can run this very script as the oracle instead of re-deriving the inventory.
const OUT = process.argv[2] ?? join(ROOT, 'contracts/reexports.json')
const APP_PRIMITIVES = '@deepseek-ai/dsh-client-ui-primitives'

/** The names inside one `{ … }` block, skipping `type X` and `X as Y` noise. */
function namesIn(block) {
  return block
    .split(',')
    .map(part => part.trim())
    .filter(part => part.length > 0 && !part.startsWith('type '))
    .map(part => part.split(/\s+as\s+/u)[0].trim())
    .filter(name => /^[A-Za-z_$][\w$]*$/u.test(name))
}

/** Every `import { … } from '<spec>'`, so an exported name can be traced back to its module. */
function importedFrom(text) {
  const map = new Map()
  const pattern = /import\s+(?:type\s+)?\{([\s\S]*?)\}\s+from\s+'([^']+)'/gu
  for (const match of text.matchAll(pattern)) {
    for (const name of namesIn(match[1])) map.set(name, match[2])
  }
  return map
}

/**
 * Every `export { … }` or `export { … } from '<spec>'`, with the specifier when the statement carries one.
 * `export type { … }` is skipped on purpose: this inventory is about values a consumer can render, and a type
 * name is never a catalogue entry.
 */
function exportedNames(text) {
  const exported = []
  const pattern = /(^|[^\w])export\s+(?!type\s)\{([\s\S]*?)\}\s*(?:from\s+'([^']+)')?/gu
  for (const match of text.matchAll(pattern)) {
    const from = match[3] ?? undefined
    for (const name of namesIn(match[2])) exported.push({ name, from })
  }
  return exported
}

function sourceOf(name, from, imports) {
  const spec = from ?? imports.get(name)
  if (spec === undefined) return 'local'
  if (spec.includes('/registry/')) return 'registry-item'
  if (spec === APP_PRIMITIVES) return APP_PRIMITIVES
  if (spec.includes('contract-adapters')) return './contract-adapters.tsx'
  return 'local'
}

const text = readFileSync(INDEX, 'utf8')
const imports = importedFrom(text)
const exported = exportedNames(text)

const groups = new Map()
const registryItems = []
for (const { name, from } of exported) {
  const source = sourceOf(name, from, imports)
  if (source === 'registry-item') { registryItems.push(name); continue }
  const list = groups.get(source) ?? []
  if (!list.includes(name)) list.push(name)
  groups.set(source, list)
}

const ordered = [...groups.entries()]
  .map(([source, names]) => ({ source, exports: names.sort((left, right) => left.localeCompare(right)) }))
  .sort((left, right) => left.source.localeCompare(right.source))

const document = {
  formatVersion: 1,
  generatedFrom: 'src/client/index.ts',
  note: 'Exports of @acryl/ui that are not registry items: a consumer can import them, and nothing can be copied with `acryl ui add`. Generated by scripts/generate-reexports.mjs; a stale copy fails tests/reexports.spec.ts.',
  registryItemExports: registryItems.sort((left, right) => left.localeCompare(right)),
  groups: ordered,
}
writeFileSync(OUT, `${JSON.stringify(document, null, 2)}\n`)
const total = ordered.reduce((sum, group) => sum + group.exports.length, 0)
console.log(`reexports.json: ${total} non-registry export(s) in ${ordered.length} group(s), ${registryItems.length} registry-item export(s)`)
for (const group of ordered) console.log(`  ${group.source}: ${group.exports.length}`)