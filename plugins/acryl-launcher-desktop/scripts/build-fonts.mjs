#!/usr/bin/env node
// Writes src/client/fonts.ts: the two typefaces acryl.dev uses (Space Grotesk, variable; JetBrains Mono 400 and 500; both SIL OFL 1.1), embedded as data URIs
// so the "acryl.dev" skin works offline. The files are the ones the site ships (@fontsource packages); run it again only to change them:
//   node scripts/build-fonts.mjs <the site's node_modules folder>
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const modules = process.argv[2]
if (modules === undefined) {
  console.error('usage: node scripts/build-fonts.mjs <acryldev.github.io/node_modules>')
  process.exit(2)
}
const faces = [
  { family: 'Space Grotesk Variable', file: '@fontsource-variable/space-grotesk/files/space-grotesk-latin-wght-normal.woff2', weight: '300 700' },
  { family: 'JetBrains Mono', file: '@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2', weight: '400' },
  { family: 'JetBrains Mono', file: '@fontsource/jetbrains-mono/files/jetbrains-mono-latin-500-normal.woff2', weight: '500' },
]
const css = faces.map(face => `@font-face { font-family: '${face.family}'; font-style: normal; font-display: swap; font-weight: ${face.weight}; src: url(data:font/woff2;base64,${readFileSync(join(resolve(modules), face.file)).toString('base64')}) format('woff2'); }`).join('\n')
const here = dirname(fileURLToPath(import.meta.url))
writeFileSync(join(here, '..', 'src', 'client', 'fonts.ts'), `/**
 * The typefaces of acryl.dev for the launcher's "acryl.dev" skin: Space Grotesk (variable) and JetBrains Mono 400 and 500, SIL Open Font License 1.1,
 * embedded as data URIs. Generated by scripts/build-fonts.mjs from the site's @fontsource packages; do not edit by hand.
 */
export const SITE_FONT_FACES = ${JSON.stringify(css)}
`)
console.log(`fonts.ts: ${String(faces.length)} faces, ${String(Math.round(css.length / 1024))} KB`)
