// Generates palette.js from the UI library's semantic role file (spec 038-ui-component-library, Q3 in research.md): one source (plugins/ui/contracts/tokens.json),
// two targets: the web roles (@acryldev/ui) and this terminal palette. Run `node scripts/compile-palette.mjs` after changing tokens.json; tests/palette.test.mjs fails
// when the committed palette.js is stale. `--check` prints nothing and exits 1 when stale. (The terminal agent, acryldev/acryl-terminal, compiles the same tokens into its
// own TypeScript palette.)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = new URL('.', import.meta.url)
const source = fileURLToPath(new URL('../../ui/contracts/tokens.json', here))
const target = fileURLToPath(new URL('../palette.js', here))

// Terminal role name for each semantic role that has a terminal color. The terminal owns its background and default text, so roles with null are skipped.
const TERMINAL_NAME = { primary: 'primary', secondary: 'secondary', accent: 'accent', reasoning: 'reasoning', success: 'success', warning: 'warning', error: 'error', info: 'info', textMuted: 'muted' }

export function renderPalette(tokens) {
  const lines = ['// GENERATED by plugins/ui-tui/scripts/compile-palette.mjs from plugins/ui/contracts/tokens.json. Do not edit; change the token file and regenerate.', '']
  for (const mode of ['dark', 'light']) {
    lines.push(`const ${mode} = {`)
    for (const [role, name] of Object.entries(TERMINAL_NAME)) {
      const hex = tokens.roles[role]?.terminal?.[mode]
      if (typeof hex !== 'string') throw new Error(`tokens.json: role ${role} has no ${mode} terminal color`)
      lines.push(`  ${name}: '${hex}',`)
    }
    lines.push('}', '')
  }
  lines.push('/** Terminal palettes by background: `dark` for a dark terminal (the default), `light` for a light one. */', 'export const palettes = { dark, light }', '')
  return lines.join('\n')
}

const expected = renderPalette(JSON.parse(readFileSync(source, 'utf8')))
if (process.argv.includes('--check')) {
  const read = path => { try { return readFileSync(path, 'utf8') } catch { return '' } }
  process.exit(read(target) === expected ? 0 : 1)
}
if (process.argv[1]?.endsWith('compile-palette.mjs')) writeFileSync(target, expected)
