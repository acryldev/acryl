/**
 * Embed the repository-owned ACRYL logo as inline data URLs, for the tree's own header brand mark
 * (T137/T138-followup: the real logo used to be visible by default, inside the upstream sidebar's own
 * chrome - T128 made that hidden behind Search, and the tree's own header never got a replacement).
 *
 * The source PNGs (`acryl-logo.png` / `acryl-logo-white.png`) live at the workspace root - the same
 * single source of truth `dsh-client-ui-brand-acryl`'s own `generate-acryl-brand-data.mjs` and
 * `acryl-desktop`'s own `generate-acryl-brand.mjs` already read for the identical purpose. This is a
 * third, independent reader of that one shared source, not a copy of either sibling script's own
 * package internals - the same pattern they already establish for a third consumer to follow.
 *
 * No PNG dimension/alpha validation here (unlike the sibling script, which uses `sharp`): a plain
 * PNG-signature check is enough for a small header mark, and adding a native image dependency to this
 * package for one codegen script is not worth it.
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const workspaceRoot = dirname(dirname(packageRoot))
const clientModule = join(packageRoot, 'src', 'client', 'agents', 'acryl-logo-data.ts')
const blackSource = join(workspaceRoot, 'acryl-logo.png')
const whiteSource = join(workspaceRoot, 'acryl-logo-white.png')

const PNG_SIGNATURE = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])

async function logo(path) {
  const data = await readFile(path)
  if (!data.subarray(0, PNG_SIGNATURE.length).equals(PNG_SIGNATURE)) {
    throw new Error(`generate-acryl-logo-data: ${path} is not a PNG`)
  }
  return data
}

const [black, white] = await Promise.all([logo(blackSource), logo(whiteSource)])

const moduleSource = `/** Generated by scripts/generate-acryl-logo-data.mjs. Do not edit manually. */\n\n`
  + `export const ACRYL_LOGO_BLACK_DATA_URL = ${JSON.stringify(`data:image/png;base64,${black.toString('base64')}`)}\n`
  + `export const ACRYL_LOGO_WHITE_DATA_URL = ${JSON.stringify(`data:image/png;base64,${white.toString('base64')}`)}\n`
await writeFile(clientModule, moduleSource)
