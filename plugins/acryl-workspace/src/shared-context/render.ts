/**
 * The shared context of a Shared Context workspace (spec 043), as text: what an agent is told about the workspace it works in. Pure: the
 * caller reads the files. Two shapes: the prompt block (inside a size budget, so it never floods a model's context) and the full document
 * written to `WORKSPACE.md`.
 */

export interface ContextProject {
  readonly name: string
  readonly path: string
  /** The project's own agent instructions present at its root (`CLAUDE.md`, `AGENTS.md`, `README.md`), referenced, never copied. */
  readonly instructions: readonly string[]
}

export interface ContextInput {
  readonly name: string
  readonly projects: readonly ContextProject[]
  /** The workspace brief, as the user wrote it; empty when there is none. */
  readonly brief: string
  /** Where the full document is, for the agent to read. */
  readonly documentPath: string
  /** Where the brief is, for the agent to know what it may edit. */
  readonly briefPath: string
}

/** The prompt block's size, in characters (about 900 tokens). */
export const CONTEXT_PROMPT_BUDGET = 3200
/** The XML-style tag of the prompt block, in the style of the other ACRYL sections. */
export const CONTEXT_TAG = 'acryl_workspace'

function projectLines(projects: readonly ContextProject[]): string[] {
  if (projects.length === 0) return ['- (no projects yet)']
  return projects.map(project => `- ${project.name}: ${project.path}${project.instructions.length === 0 ? '' : ` (instructions: ${project.instructions.join(', ')})`}`)
}

/** The block the DSH chat and terminal agents get. The brief is cut to fit the budget, and says so. */
export function renderContextPrompt(input: ContextInput, budget = CONTEXT_PROMPT_BUDGET): string {
  const head = [
    `<${CONTEXT_TAG}>`,
    `You work in the ACRYL workspace "${input.name}", a shared-context workspace: these projects belong together. Read and search any of them when a task crosses them; follow each project's own instructions when you work in it.`,
    'Projects:',
    ...projectLines(input.projects),
  ]
  const tail = [`Full context: ${input.documentPath}. The brief is ${input.briefPath} (the user's; edit it only when asked).`, `</${CONTEXT_TAG}>`]
  const brief = input.brief.trim()
  if (brief === '') return [...head, ...tail].join('\n')
  // What is left for the brief: the block without it, plus the one line break that joins the brief in.
  const room = budget - [...head, 'Brief:', ...tail].join('\n').length - 1
  const note = '\n(brief cut here; the rest is in the file)'
  if (room <= note.length + 40) return [...head, ...tail].join('\n')
  const cut = brief.length <= room ? brief : `${brief.slice(0, room - note.length).trimEnd()}${note}`
  return [...head, 'Brief:', cut, ...tail].join('\n')
}

/** The whole document written to `WORKSPACE.md`: the brief in full. */
export function renderContextDocument(input: ContextInput): string {
  const brief = input.brief.trim()
  return [
    `# Workspace: ${input.name}`,
    '',
    'Generated by ACRYL for every agent working in this shared-context workspace. Do not edit: it is rewritten when the workspace changes.',
    `The brief is ${input.briefPath}.`,
    '',
    '## Projects',
    '',
    ...projectLines(input.projects),
    '',
    '## Brief',
    '',
    brief === '' ? '(none yet)' : brief,
    '',
  ].join('\n')
}
