/**
 * Embed the repository-owned ACRYL logos as inline data URLs.
 *
 * The source PNGs (`acryl-logo.png` / `acryl-logo-white.png`) live at the
 * workspace root - the same single source of truth `acryl-desktop`'s own
 * `generate-acryl-brand.mjs` reads for its native app icon/tray artwork.
 * This script only needs the browser-embeddable data URLs, not the native
 * icon variants, so it stops after generating the client module.
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const workspaceRoot = dirname(packageRoot)
const clientModule = join(packageRoot, 'src', 'client', 'acryl-logo-data.ts')
const blackSource = join(workspaceRoot, 'acryl-logo.png')
const whiteSource = join(workspaceRoot, 'acryl-logo-white.png')

const PNG_SIGNATURE = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])

async function logo(path) {
  const data = await readFile(path)
  if (!data.subarray(0, PNG_SIGNATURE.length).equals(PNG_SIGNATURE)) {
    throw new Error(`generate-acryl-brand-data: ${path} is not a PNG`)
  }
  const metadata = await sharp(data).metadata()
  if (metadata.width !== 974 || metadata.height !== 974 || metadata.hasAlpha !== true) {
    throw new Error(`generate-acryl-brand-data: ${path} must be the supplied 974x974 transparent logo`)
  }
  return data
}

const [black, white] = await Promise.all([logo(blackSource), logo(whiteSource)])

const moduleSource = `/** Generated by scripts/generate-acryl-brand-data.mjs. Do not edit manually. */\n\n`
  + `export const ACRYL_LOGO_BLACK_DATA_URL = ${JSON.stringify(`data:image/png;base64,${black.toString('base64')}`)}\n`
  + `export const ACRYL_LOGO_WHITE_DATA_URL = ${JSON.stringify(`data:image/png;base64,${white.toString('base64')}`)}\n`
await writeFile(clientModule, moduleSource)
