#!/usr/bin/env node
// The launcher as one file with nothing to install: run.js with the journeys, @acryldev/ui-tui and the workspace's patched pi-tui inlined. The acryl npm
// package ships this file as launcher.js and opens it for a bare `acryl` in a terminal, so `npx acryl` stays small and needs no dependency.
// Usage: node scripts/bundle.mjs <output file>
import { copyFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'rolldown'

const here = dirname(fileURLToPath(import.meta.url))

/** Write the bundle to `file` and return its path. */
export async function bundleLauncher(file) {
  const out = resolve(file)
  await build({
    input: resolve(here, 'run.js'),
    platform: 'node',
    logLevel: 'warn',
    // The Control Center's service from its TypeScript source, so packing `acryl` needs no build of @acryldev/launcher-desktop (whose lib/ also holds
    // the browser bundles); the package's `./node` export is the same file, built.
    resolve: { alias: { '@acryldev/launcher-desktop/node': resolve(here, '..', '..', '..', 'plugins', 'launcher-desktop', 'src', 'node.ts') } },
    output: {
      file: out,
      format: 'esm',
      codeSplitting: false,
      banner: "// acryl Control Center in the terminal: generated by distribution/acryl-npm-launcher/tui/bundle.mjs. Do not edit; change the sources and bundle again.",
    },
  })
  // The opener every launcher runs (plugins/launcher/os-launchers.js copies these into ~/.acryl/shortcuts) is read from beside this file, and so is the
  // one install of apps (managed.js INSTALL_CLI runs app-install-cli.mjs, which imports app-install.js).
  for (const file of ['shortcut-open.mjs', 'model-key.js', 'app-install.js', 'app-install-cli.mjs']) copyFileSync(resolve(here, '..', '..', '..', 'plugins', 'launcher', file), resolve(dirname(out), file))
  return out
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const target = process.argv[2]
  if (!target) {
    console.error('usage: node scripts/bundle.mjs <output file>')
    process.exitCode = 2
  } else console.log(await bundleLauncher(target))
}
