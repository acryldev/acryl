#!/usr/bin/env node
// Stamps every build with the exact commit and time it was built from, shown
// in the TUI's own header. This session repeatedly lost time to "is this
// build actually current" -- multiple terminal tabs left running stale
// processes from before a fix landed, with no way to tell from a screenshot
// alone. Regenerated on every `pnpm run build` (wired as a `prebuild` step),
// so the header's own commit/time is the answer, not a guess from `ps`/`git log`.
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const outFile = join(here, '..', 'src', 'buildInfo.generated.ts')

function gitShortHash() {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: here, stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim()
  } catch {
    return undefined // not a git checkout (e.g. a packaged release with no .git) -- omit, don't fail the build
  }
}

const commit = gitShortHash()
const builtAt = new Date().toISOString()

writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-build-info.mjs on every \`pnpm run build\` -- do not hand-edit.
/** Short git commit this build was produced from, or undefined outside a git checkout. */
export const BUILD_COMMIT: string | undefined = ${commit === undefined ? 'undefined' : JSON.stringify(commit)}
/** ISO timestamp this build was produced at. */
export const BUILD_TIME: string = ${JSON.stringify(builtAt)}
`,
)
process.stdout.write(`build-info: ${commit ?? '(no git)'} @ ${builtAt}\n`)
